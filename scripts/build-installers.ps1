# Drawplate installer generator
# Concatenates modules into scripts/dist/install.sh and scripts/dist/install.ps1
# Compatible with Windows PowerShell 5.1 and PowerShell 7+

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$scriptDir = Split-Path -Parent $PSCommandPath
$repoRoot = Split-Path -Parent $scriptDir
$srcSh = Join-Path $repoRoot 'scripts\src\sh'
$srcPs1 = Join-Path $repoRoot 'scripts\src\ps1'
$distDir = Join-Path $repoRoot 'scripts\dist'
$outSh = Join-Path $distDir 'install.sh'
$outPs1 = Join-Path $distDir 'install.ps1'

$commit = ''
try { $commit = (git -C $repoRoot rev-parse --short HEAD 2>$null) } catch { }
if (-not $commit) { $commit = 'unknown' }

$modules = @('00-header','10-ui','20-platform','30-net','40-verify','50-install','60-path','70-setup-offer','80-uninstall','90-main')

New-Item -ItemType Directory -Path $distDir -Force | Out-Null

# Generate install.sh
$shHeader = "#!/bin/sh`n# Drawplate installer - generated by scripts/build-installers.ps1`n# Modules: $(($modules -join ' '))`n# Commit: $commit`n"
$shContent = $shHeader
foreach ($m in $modules) {
    $modFile = Join-Path $srcSh ($m + '.sh')
    if (Test-Path $modFile) {
        $shContent += "`n### $m ###`n"
        $shContent += Get-Content $modFile -Raw
    }
}
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($outSh, $shContent, $utf8)

# Generate install.ps1
$ps1Header = "# Drawplate installer - generated by scripts/build-installers.ps1`n# Modules: $(($modules -join ' '))`n# Commit: $commit`n"
$ps1Content = $ps1Header
foreach ($m in $modules) {
    $modFile = Join-Path $srcPs1 ($m + '.ps1')
    if (Test-Path $modFile) {
        $ps1Content += "`n### $m ###`n"
        $ps1Content += Get-Content $modFile -Raw
    }
}
[System.IO.File]::WriteAllText($outPs1, $ps1Content, $utf8)

Write-Host "Generated $outSh"
Write-Host "Generated $outPs1"
