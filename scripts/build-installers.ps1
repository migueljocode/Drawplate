# Drawplate installer generator
# Copies the maintained single-file installers into scripts/dist.
# Compatible with Windows PowerShell 5.1 and PowerShell 7+.

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$scriptDir = Split-Path -Parent $PSCommandPath
$repoRoot = Split-Path -Parent $scriptDir
$srcSh = Join-Path $repoRoot 'scripts\src\sh\install.sh'
$srcPs1 = Join-Path $repoRoot 'scripts\src\ps1\install.ps1'
$distDir = Join-Path $repoRoot 'scripts\dist'
$outSh = Join-Path $distDir 'install.sh'
$outPs1 = Join-Path $distDir 'install.ps1'

New-Item -ItemType Directory -Path $distDir -Force | Out-Null
$utf8 = New-Object System.Text.UTF8Encoding($false)

$shLines = [System.IO.File]::ReadAllLines($srcSh)
if ($shLines.Length -lt 4 -or $shLines[0] -ne '#!/bin/sh') {
    throw 'scripts/src/sh/install.sh has an unexpected header.'
}
$shBody = ($shLines | Select-Object -Skip 3) -join "`n"
$shContent = "#!/bin/sh`n# Generated by scripts/build-installers.ps1. Do not edit.`n`n$shBody`n"
[System.IO.File]::WriteAllText($outSh, $shContent, $utf8)

$psLines = [System.IO.File]::ReadAllLines($srcPs1)
if ($psLines.Length -lt 4 -or $psLines[0] -ne '# Drawplate installer - generated by scripts/build-installers.ps1') {
    throw 'scripts/src/ps1/install.ps1 has an unexpected header.'
}
$psBody = ($psLines | Select-Object -Skip 3) -join "`n"
$psContent = "# Generated by scripts/build-installers.ps1. Do not edit.`n$psBody`n"
[System.IO.File]::WriteAllText($outPs1, $psContent, $utf8)

Write-Host "Generated $outSh"
Write-Host "Generated $outPs1"
