Describe 'Drawplate installer distribution' {
    BeforeAll {
        $script:repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '../../..')).Path
        $script:installer = Join-Path $script:repoRoot 'scripts/dist/install.ps1'
        $script:content = [System.IO.File]::ReadAllText($script:installer)
    }

    It 'is ASCII-only' {
        [System.Text.Encoding]::ASCII.GetString([System.Text.Encoding]::ASCII.GetBytes($script:content)) | Should -Be $script:content
    }

    It 'has the generated-file header' {
        $script:content | Should -Match '^# Generated by scripts/build-installers.ps1'
    }

    It 'starts with strict mode and terminating errors' {
        $script:content | Should -Match 'Set-StrictMode -Version 2.0'
        $script:content | Should -Match '\$ErrorActionPreference\s*=\s*''Stop'''
        $script:content | Should -Match '\$ProgressPreference\s*=\s*''SilentlyContinue'''
    }

    It 'does not use syntax unavailable in Windows PowerShell 5.1' {
        $script:content | Should -Not -Match '\?\:|\?\?|\?\.|\?\[|&&|\|\|'
    }

    It 'does not use the forbidden download cmdlet' {
        $script:content | Should -Not -Match '\bInvoke-WebRequest\b'
    }
}
